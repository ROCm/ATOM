#!/usr/bin/env bash
# Qwen3.5 gfx1250 c512 baseline recipe with the embedded LMCache CPU tier.
set -euo pipefail
RECIPE_DIR=$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)
export ATOM_DIR=${ATOM_DIR:-$(cd "$RECIPE_DIR/../.." && pwd)}
export LMCACHE_VENV=${LMCACHE_VENV:-/work/lmcache-venv}
export PATH="$LMCACHE_VENV/bin:$PATH"
export R=${R:-/work/qwen35_ep}
export RUNS=${RUNS:-/work/offload_c512_$(date -u +%Y%m%d_%H%M%S)}
export CAP_MIN=${CAP_MIN:-10} TURN_TIMEOUT=${TURN_TIMEOUT:-900}
export STOP_FIRST=${STOP_FIRST:-0}
export ATOM_DP_PREFILL_BALANCE_TOKEN_WEIGHT=${ATOM_DP_PREFILL_BALANCE_TOKEN_WEIGHT:-28000}
export ATOM_PREFILL_DECODE_INTERVAL=${ATOM_PREFILL_DECODE_INTERVAL:-16}
export ATOM_KV_OFFLOAD=lmcache
export LMCACHE_LOCAL_CPU=True
export LMCACHE_MAX_LOCAL_CPU_SIZE=${LMCACHE_MAX_LOCAL_CPU_SIZE:-128}
export LMCACHE_CHUNK_SIZE=${LMCACHE_CHUNK_SIZE:-1024}
export LMCACHE_CACHE_POLICY=${LMCACHE_CACHE_POLICY:-LRU}
export LMCACHE_ENABLE_ASYNC_LOADING=False LMCACHE_SAVE_DECODE_CACHE=False
export LMCACHE_TRACK_USAGE=false LMCACHE_LOG_LEVEL=${LMCACHE_LOG_LEVEL:-WARNING}
export PYTHONHASHSEED=${PYTHONHASHSEED:-0}
export OFFLOAD_STATE_CPU_SIZE=${OFFLOAD_STATE_CPU_SIZE:-80}
export OFFLOAD_STATE_GPU_SIZE=${OFFLOAD_STATE_GPU_SIZE:-64}
export OFFLOAD_PROFILE=${OFFLOAD_PROFILE:-1}
mkdir -p "$RUNS"
env | sort | grep -E '^((ATOM|AITER|FLYDSL|HIP|HSA|MORI|MEGA|TRITON|LMCACHE|OFFLOAD)_|CAP_MIN=|TURN_TIMEOUT=|STOP_FIRST=|PATH=|PYTHONPATH=|PYTHONHASHSEED=|RUNS=|R=)' > "$RUNS/offload_env.txt"
exec bash /app/qwen35_work/c512_20261031/run_c512.sh
