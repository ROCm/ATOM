"""Packaging of the `atom` command: the per-user launcher
(scripts/install_atom_command.sh) and the Debian package amd-atom
(scripts/build_deb.sh)."""

import os
import shutil
import subprocess
import sys
from pathlib import Path

import pytest

REPO = Path(__file__).resolve().parents[2]
INSTALL = REPO / "scripts" / "install_atom_command.sh"


def _run(*args, env=None):
    return subprocess.run(
        ["bash", str(INSTALL), *args],
        capture_output=True,
        text=True,
        env={**os.environ, **(env or {})},
        check=False,
    )


def test_install_runs_from_anywhere_and_uninstalls(tmp_path):
    bin_dir = tmp_path / "bin"
    res = _run(str(bin_dir))
    assert res.returncode == 0, res.stderr
    launcher = bin_dir / "atom"
    assert os.access(launcher, os.X_OK)
    # Works from an unrelated cwd, with no ATOM on the default path.
    out = subprocess.run(
        [str(launcher), "--help"],
        cwd=tmp_path,
        capture_output=True,
        text=True,
        env={k: v for k, v in os.environ.items() if k != "PYTHONPATH"},
        check=False,
    )
    assert out.returncode == 0 and out.stdout.startswith("usage: atom")
    assert _run(str(bin_dir)).returncode == 0  # reinstall over our own file
    assert "removed" in _run("--uninstall", str(bin_dir)).stdout
    assert not launcher.exists()


def test_install_refuses_to_overwrite_a_foreign_command(tmp_path):
    bin_dir = tmp_path / "bin"
    bin_dir.mkdir()
    foreign = bin_dir / "atom"
    foreign.write_text("#!/bin/sh\necho someone else's tool\n")
    res = _run(str(bin_dir))
    assert res.returncode != 0 and "not installed by this script" in res.stderr
    assert "someone else" in foreign.read_text()
    assert "nothing to remove" in _run("--uninstall", str(bin_dir)).stdout
    assert foreign.exists()
    assert _run("--force", str(bin_dir)).returncode == 0


def test_install_rejects_old_python(tmp_path):
    fake = tmp_path / "python3"
    fake.write_text("#!/bin/sh\nexit 1\n")  # fails the version check
    fake.chmod(0o755)
    res = _run(str(tmp_path / "bin"), env={"PYTHON": str(fake)})
    assert res.returncode != 0 and "needs Python 3.10+" in res.stderr


def test_install_replaces_the_earlier_amd_atom_launcher(tmp_path):
    bin_dir = tmp_path / "bin"
    bin_dir.mkdir()
    legacy = bin_dir / "amd-atom"
    legacy.write_text(
        "#!/bin/sh\n# amd-atom launcher generated by scripts/install_amd_atom.sh\n"
    )
    foreign = bin_dir / "unrelated"
    foreign.write_text("#!/bin/sh\n")
    res = _run(str(bin_dir))
    assert res.returncode == 0, res.stderr
    assert "removed the earlier launcher" in res.stdout
    assert not legacy.exists() and (bin_dir / "atom").exists() and foreign.exists()


def test_launcher_is_not_shadowed_by_the_cwd(tmp_path):
    """Running `atom` inside another checkout must not import that checkout."""
    bin_dir = tmp_path / "bin"
    assert _run(str(bin_dir)).returncode == 0
    decoy = tmp_path / "decoy"
    (decoy / "atom").mkdir(parents=True)
    (decoy / "atom" / "__init__.py").write_text("raise SystemExit('SHADOWED')\n")
    out = subprocess.run(
        [str(bin_dir / "atom"), "--help"],
        cwd=decoy,
        capture_output=True,
        text=True,
        env={**os.environ, "PYTHONPATH": str(decoy)},
        check=False,
    )
    assert out.returncode == 0 and "SHADOWED" not in out.stdout + out.stderr


@pytest.mark.skipif(not shutil.which("dpkg-deb"), reason="needs dpkg-deb")
def test_deb_package_is_complete(tmp_path):
    """Build amd-atom_<v>_all.deb, check its metadata, then run the agent
    from the extracted files alone (proves the shipped import closure)."""
    out = tmp_path / "out"
    res = subprocess.run(
        ["bash", str(REPO / "scripts" / "build_deb.sh"), str(out)],
        capture_output=True,
        text=True,
        env={
            **os.environ,
            "VERSION": "0.0.1~test",
            "MAINTAINER": "Test <t@example.com>",
        },
        check=False,
    )
    assert res.returncode == 0, res.stderr
    deb = out / "amd-atom_0.0.1~test_all.deb"
    field = lambda f: subprocess.run(  # noqa: E731
        ["dpkg-deb", "-f", str(deb), f], capture_output=True, text=True, check=True
    ).stdout.strip()
    assert field("Package") == "amd-atom" and field("Architecture") == "all"
    assert field("Conflicts") == "atom" and field("Depends").startswith(
        "python3 (>= 3.10)"
    )
    root = tmp_path / "root"
    subprocess.run(["dpkg-deb", "-x", str(deb), str(root)], check=True)
    launcher = (root / "usr" / "bin" / "atom").read_text()
    assert "/usr/lib/amd-atom" in launcher and "-I" in launcher
    lib = root / "usr" / "lib" / "amd-atom"
    probe = (
        "import sys; sys.path.insert(0, sys.argv.pop(1)); "
        "from atom.agent.config import repo_root; from atom.agent.knowledge import "
        "load_knowledge; import atom.agent.evals, atom.agent.mcp_server; "
        "kb = load_knowledge(repo_root()); print(len(kb.list_recipes())); "
        "from atom.agent.cli import main; main()"
    )
    run = subprocess.run(
        [sys.executable, "-I", "-c", probe, str(lib), "--help"],
        cwd=tmp_path,
        capture_output=True,
        text=True,
        check=False,
    )
    assert run.returncode == 0, run.stderr
    recipes, usage = run.stdout.split("\n", 1)
    assert int(recipes) > 10 and usage.startswith("usage: atom")
    assert (lib / ".claude" / "skills" / "run-atom-workload" / "SKILL.md").is_file()
