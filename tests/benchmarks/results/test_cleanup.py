ROOT = Path(__file__).resolve().parents[3]
FIXTURES = Path(__file__).parent / "fixtures"


def dashboard_module():
    spec = importlib.util.spec_from_file_location(
        "aiperf_dashboard", ROOT / ".github/scripts/aiperf_dashboard.py"
    )
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def test_shared_export_matches_original_pd_summary():
    # Expected output was generated by main's original embedded Python exporter.
    fixture = read_json(FIXTURES / "aiperf-dashboard.json")
    result = dashboard_module().dashboard_summary(
        fixture["source"],
        Path("aiperf/profile_export_aiperf.json"),
        fixture["concurrency"],
        fixture["environment"],
    )
    assert result == fixture["expected"]


@pytest.mark.parametrize("arguments", ["-tp 2", "--tensor-parallel-size=2"])
def test_single_node_export_preserves_counts_and_invalidity(arguments):
    fixture = read_json(FIXTURES / "aiperf-dashboard.json")
    source = {**fixture["source"], "metadata": {"submission_valid": False}}
    result = dashboard_module().dashboard_summary(
        source,
        Path("aiperf/profile_export_aiperf.json"),
        2,
        {"SERVER_ARGS": arguments},
        single_node=True,
    )
    assert result["tensor_parallel_size"] == 2
    assert result["p90_itl_ms"] == fixture["expected"]["p90_itl_ms"]
    assert result["successful_requests"] == 40
    assert result["dashboard_publish_allowed"] is False


def test_buffered_records_flush_on_close_and_periodic_write(tmp_path, monkeypatch):
    now = [0.0]
    monkeypatch.setattr("atom.benchmarks.results.io.time.monotonic", lambda: now[0])
    path = tmp_path / "records.jsonl"
    writer = JsonlWriter(path)
    for i in range(10):
        writer.write({"request_id": str(i)})
    assert path.stat().st_size == 0
    now[0] = 2.0
    writer.write({"request_id": "10"})
    assert len(list(iter_jsonl(path))) == 11
    writer.write({"request_id": "11"})
    writer.close()
    assert len(list(iter_jsonl(path))) == 12


