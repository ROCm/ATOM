def test_resolved_client_overrides_survive_launch_capture(tmp_path):
    from atom.benchmarks.results.__main__ import main

    launch = tmp_path / "client.json"
    assert (
        main(
            [
                "capture-launch",
                "--output",
                str(launch),
                "--",
                "python",
                "--max-concurrency",
                "4",
                "--random-input-len=2048",
                "--num-prompts",
                "40",
                "--ignore-eos",
            ]
        )
        == 0
    )
    config = read_json(FIXTURES / "random-config.json")
