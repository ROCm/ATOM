def validate_partition(partition):
    if len(partition) != 4 or any(len(ids) != 96 for ids in partition):
        raise ValueError("Fixed EP4 placement requires exactly 96 experts per rank")
    flat = [expert for ids in partition for expert in ids]
    if any(type(expert) is not int for expert in flat):
        raise ValueError("Expert IDs must be integers")
    if sorted(flat) != list(range(384)):
        raise ValueError("Fixed EP4 placement must own every expert exactly once")
    if any(tuple(sorted(ids)) != tuple(ids) for ids in partition):
        raise ValueError("Native mask indexing requires ascending local expert IDs")


def expected_experts(layer, rank):
    if type(layer) is not int or layer not in range(40):
        raise ValueError("Expected target layer 0..39")
    if type(rank) is not int or rank not in range(4):
        raise ValueError("Expected EP4 rank 0..3")
    if layer not in range(2, 20):
        return list(range(rank * 96, (rank + 1) * 96))
    return list(EXPERTS_BY_LAYER[layer - 2][rank])


def install_owner_placement(model, config):
    """One startup mutation, before the native loader reads expert_map."""
    import torch

    from .owner_ep import validate_owner_ep4

    if getattr(model, "owner_ep4_placement", None) is not None:
        raise ValueError("Expert placement is already installed")
    # This first validation still requires the original contiguous mapping.
    contract = validate_owner_ep4(model, config)
    if any(
        getattr(layer.ffn.experts.w13_weight, "is_shuffled", False)
        or getattr(layer.ffn.experts.w2_weight, "is_shuffled", False)
        for layer in model.layers
    ):
        raise ValueError("Expert placement must precede native weight processing")
    if len(EXPERTS_BY_LAYER) != 18:
        raise ValueError("Expected exactly the 18 retained-prefill layers")
    for partition in EXPERTS_BY_LAYER:
        validate_partition(partition)
    rank = contract["rank"]
    for layer in range(2, 20):
        experts = model.layers[layer].ffn.experts
        ids = expected_experts(layer, rank)
        mapping = [-1] * 385
        for local, global_id in enumerate(ids):
            mapping[global_id] = local
        experts.expert_map.copy_(
            torch.tensor(mapping, dtype=torch.int32, device=experts.expert_map.device)
        )
        experts.expert_mask.copy_((experts.expert_map >= 0).to(torch.int32))
    model.owner_ep4_placement = PLAN_ID
