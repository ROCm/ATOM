"""K2's MLA fold builds: ``layer.build`` for a key with ``mla_post`` /
``mla_prep``. The same kernel body (``layer._body``), with the post stage's
arguments past K2's (``layer.ABI_POST``), then the prep stages'
(``layer.ABI_PREP``), each spelled out as FlyDSL's kernel signatures need; and
a build's LLVM machine scheduler (``key.sched``, ``layer.FOLD_SCHEDULERS``)."""

import flydsl.compiler as flyc
import flydsl.expr as fx
from flydsl.expr.typing import Int32, Int64

from atom.models.kimi_k3.mono.kernels.layer import (
    _STREAM,
    ABI_POST,
    ABI_PREP,
    FOLD_SCHEDULERS,
    _body,
)
from atom.mono.plan.execution import BLOCKS, THREADS


def build(key, name: str, keyed, bk: dict):
    """The launcher of fold key ``key`` (kernel ``name``, FlyDSL cache key
    ``keyed``; ``bk``: ``layer.build``'s constants for ``layer._body``)."""
    launch = (_build_prep if key.mla_prep else _build_post)(key, name, keyed, bk)
    _schedule(key, launch)
    return launch


def _schedule(key, launch) -> None:
    """``key.sched`` as the fold build's ``amdgpu-sched-strategy``: a compile
    hint, so FlyDSL keys its cache on it as well."""
    if key.sched:
        assert key.sched in FOLD_SCHEDULERS, key.sched
        flyc.compile[{"llvm_options": {"amdgpu-sched-strategy": key.sched}}](launch)


