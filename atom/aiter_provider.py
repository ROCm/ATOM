"""Enable out-of-tree aiter kernel providers for ATOM.

Opt-in and default OFF. ATOM never imports ``aiter.plugin`` at module scope:
released aiter has no provider interface, so every CPU ``import atom`` (and
every deployment without the interface stack) must keep working. The single
enable call lives here and is made once per worker process from
``ModelRunner.__init__``, after device/distributed setup and before the model
is built -- long before the first routed call, warm-up or CUDAGraph capture.

Contract with aiter (``aiter.plugin`` on the provider-interface PR stack):

* ``configure(*, source, enable=())`` is the only way to enable a provider;
  ``enable`` is the ordered preference list and replaces prior state.
* ``AITER_PLUGINS=0`` is the only environment control and can only turn
  routing OFF; it records no ``Decision``. It is aiter's variable, not ATOM's.
* A missing/broken provider, a mismatched ``API_VERSION`` or a routed op that
  this aiter does not carry is a log line, never an ATOM failure.

The interface deliberately has no lifecycle hook, so the framework that
enables a provider also owns its ``warmup()``/``prepare()``/``shutdown()``.
Those helpers live here too: they load the installed provider object from the
same ``aiter.plugins`` entry-point group aiter discovers it from, and every
failure is a warning that leaves ATOM's native path in effect.
"""

import logging

logger = logging.getLogger("atom.aiter_provider")

# aiter.plugin.API_VERSION this module was written against. A mismatch is a
# fail-open warning: aiter and ATOM move independently.
_SUPPORTED_PLUGIN_API = 1

# Routed ops ATOM expects to find when it enables providers. A missing one is
# only a warning (the installed aiter may be older than the ATOM branch); such
# an "enabled" run would silently serve native for that op otherwise.
_EXPECTED_ROUTED_OPS = ("a2a_gemm_fused",)


def atom_version() -> str:
    """ATOM's version for the configure() provenance string.

    ``atom/_version.py`` is generated by setuptools_scm and git-ignored, so a
    source checkout lacks it: fall back to installed metadata, then "unknown".
    """
    try:
        from atom._version import __version__

        return str(__version__)
    except Exception:  # noqa: BLE001 - absent in source checkouts / CPU tests
        logger.debug("atom/_version.py is absent; using package metadata")
    try:
        from importlib.metadata import version

        return version("atom")
    except Exception:  # noqa: BLE001 - not installed, e.g. a bare checkout
        return "unknown"


def normalize_provider_names(value) -> tuple[str, ...]:
    """Normalize a provider-enable value to a tuple of names.

    Accepted: ``None``/empty (off), a comma-separated string (CLI/env form), or
    any iterable of strings (``Config`` form). Names are stripped, blanks
    dropped and duplicates removed -- order is the preference order aiter uses.
    """
    if value is None:
        return ()
    if isinstance(value, str):
        raw_names: list[object] = value.split(",")
    else:
        raw_names = list(value)
    names: list[str] = []
    for raw in raw_names:
        if raw is None:
            continue
        if not isinstance(raw, str):
            raise TypeError(
                f"aiter provider names must be strings, got {type(raw).__name__}"
            )
        name = raw.strip()
        if not name:
            continue
        if name not in names:
            names.append(name)
    return tuple(names)


def configure_aiter_providers(config) -> bool:
    """Enable aiter providers for this process, per ``config``.

    Returns True when ``configure()`` was called successfully, False otherwise.
    Never raises: missing/broken interfaces and provider errors are warnings and
    the native path stays in effect (aiter's default-deny).
    """
    try:
        enable = normalize_provider_names(
            getattr(config, "aiter_provider_enable", ()) or ()
        )
    except (TypeError, ValueError) as exc:
        logger.warning("aiter providers: unusable enable list (%s); native path", exc)
        return False
    if not enable:
        # Default OFF: never call configure(). aiter's free path then records
        # no Decision and runs every routed op native.
        return False

    try:
        import importlib

        import aiter

        try:
            plugin = importlib.import_module("aiter.plugin")
        except Exception:  # noqa: BLE001 - test doubles/absent submodule
            # A module attribute is only valid when something imported the
            # submodule already; keep it as the fallback for test doubles.
            plugin = getattr(aiter, "plugin", None)
        if plugin is None:
            raise AttributeError("aiter.plugin")
    except Exception:  # noqa: BLE001 - released aiter has no provider interface
        logger.warning(
            "aiter providers requested (%s) but this aiter has no aiter.plugin; "
            "native path",
            enable,
        )
        return False

    api = getattr(plugin, "API_VERSION", None)
    if api != _SUPPORTED_PLUGIN_API:
        logger.warning(
            "aiter providers: aiter plugin API %r != supported %d; native path",
            api,
            _SUPPORTED_PLUGIN_API,
        )
        return False

    # A routed op can be a LAZY export: `@plugin.route` registration happens only
    # when `aiter.<op>` is resolved, so status()["routed_ops"] is empty until
    # then. Resolve the ops ATOM expects before reading status, so the preflight
    # log sees the truth and the first explain() cannot KeyError.
    for name in _EXPECTED_ROUTED_OPS:
        try:
            getattr(aiter, name)
        except Exception:  # noqa: BLE001 - absent/optional export; status() decides
            logger.debug("aiter provider op %r is not importable yet", name)

    try:
        plugin.configure(source=f"atom {atom_version()}", enable=enable)
        status = plugin.status()
    except Exception:
        logger.warning(
            "aiter providers: configure()/status() failed (%s); native path",
            enable,
            exc_info=True,
        )
        return False

    routed = getattr(status, "get", lambda *_: None)("routed_ops") or {}
    missing = [op for op in _EXPECTED_ROUTED_OPS if op not in routed]
    if missing:
        logger.warning(
            "aiter is missing routed ops %s; those ops stay native on this build",
            missing,
        )
    logger.info(
        "aiter providers: enabled=%s api_accepted=%s routed=%s skipped=%s",
        getattr(status, "get", lambda *_: None)("enabled"),
        getattr(status, "get", lambda *_: None)("api_versions_accepted"),
        tuple(routed),
        getattr(status, "get", lambda *_: None)("skipped_providers"),
    )
    return True


def explain_aiter_provider_status(config) -> str | None:
    """One-line provider status for the startup log, or None when off.

    Reads ``aiter.plugin.status()`` only; never raises and never enables
    anything (``configure_aiter_providers`` is the only enable call).
    """
    enable = _enabled_providers(config)
    if not enable:
        return None
    try:
        import importlib

        plugin = importlib.import_module("aiter.plugin")
        status = plugin.status() or {}
    except Exception:  # noqa: BLE001 - no interface in this build/process
        return "aiter.plugin unavailable"
    routed = status.get("routed_ops") or {}
    return (
        f"enabled={tuple(status.get('enabled', ()) or ())} "
        f"routed={tuple(routed)} skipped={tuple(status.get('skipped_providers', ()) or ())}"
    )


def _enabled_providers(config) -> tuple[str, ...]:
    try:
        return normalize_provider_names(
            getattr(config, "aiter_provider_enable", ()) or ()
        )
    except (TypeError, ValueError):
        return ()


def _load_provider(name: str):
    """Load the installed entry-point object for ``name``, or None.

    The aiter interface has no lifecycle hook, so the framework that enables a
    provider also owns its ``warmup()``/``prepare()``/``shutdown()``. Loading
    through the same ``aiter.plugins`` group keeps this out of ATOM's import
    path until a provider is actually enabled.
    """
    try:
        from importlib.metadata import entry_points

        matches = [ep for ep in entry_points(group="aiter.plugins") if ep.name == name]
    except Exception:
        logger.warning("aiter providers: cannot enumerate aiter.plugins", exc_info=True)
        return None
    if not matches:
        logger.warning("aiter providers: no aiter.plugins entry point named %r", name)
        return None
    try:
        provider = matches[0].load()
    except Exception:
        logger.warning("aiter providers: loading %r failed", name, exc_info=True)
        return None
    # Documented shape: an instance, or a zero-argument factory returning one.
    if callable(provider) and not hasattr(provider, "select"):
        try:
            provider = provider()
        except Exception:
            logger.warning("aiter providers: factory %r failed", name, exc_info=True)
            return None
    return provider


def load_aiter_provider(config, *, op: str | None = None):
    """The first enabled provider object that serves ``op``, or None.

    Loads from ``aiter.plugins``; fail-open and never raises. Used by ATOM
    call sites that own the provider's lifecycle (warm-up, registered producer
    view), which the aiter plugin interface leaves to the framework.
    """
    for name in _enabled_providers(config):
        provider = _load_provider(name)
        if provider is None:
            continue
        if op is None:
            return provider
        op_versions = getattr(provider, "op_versions", None)
        if isinstance(op_versions, dict) and op in op_versions:
            return provider
        # A provider that does not advertise op_versions is asked anyway; its
        # warm-up/registered-view methods decide.
        if op_versions is None:
            return provider
    return None


def warmup_aiter_providers(config, payload, *, group=None, device=None) -> bool:
    """Run the enabled providers' framework-owned ``warmup()`` before capture.

    The aiter plugin interface deliberately has no lifecycle hook; a provider
    declines every routed call until the framework warms it. Fail-open: a
    missing/broken provider (or a CPU process) leaves the non-fused path in
    place, and returns False.
    """
    enabled = _enabled_providers(config)
    if not enabled:
        return False
    warmed = False
    for name in enabled:
        provider = _load_provider(name)
        warm = getattr(provider, "warmup", None)
        if not callable(warm):
            logger.warning(
                "aiter providers: %r has no warmup(); routed calls stay native", name
            )
            continue
        try:
            ok = bool(warm(payload, group=group, device=device))
        except Exception:
            logger.warning("aiter providers: %r warmup() failed", name, exc_info=True)
            ok = False
        logger.info("aiter providers: %s warmup=%s", name, ok)
        warmed = warmed or ok
    return warmed


def prepare_aiter_providers(config, payload, *, group=None, device=None) -> bool:
    """Pre-bind the enabled providers for a capture M class (prepare-only API).

    The interface has no capture hook; a compatible provider exposes
    ``prepare(payload, *, group=None, device=None) -> bool`` (no launch,
    cache-hit safe). Fail-open: a missing API or False leaves ATOM's capture
    path non-fused for that cell. Returns True when a provider prepared.
    """
    enabled = _enabled_providers(config)
    if not enabled:
        return False
    prepared = False
    for name in enabled:
        provider = _load_provider(name)
        prepare = getattr(provider, "prepare", None)
        if not callable(prepare):
            continue
        try:
            ok = bool(prepare(payload, group=group, device=device))
        except Exception:
            logger.warning(
                "aiter providers: %r prepare() failed; capture non-fused",
                name,
                exc_info=True,
            )
            ok = False
        logger.info("aiter providers: %s capture prepare=%s", name, ok)
        prepared = prepared or ok
    return prepared


def shutdown_aiter_providers(config, *, group=None, device=None) -> None:
    """Best-effort provider teardown (the interface has no lifecycle hook)."""
    for name in _enabled_providers(config):
        provider = _load_provider(name)
        shutdown = getattr(provider, "shutdown", None)
        if not callable(shutdown):
            continue
        try:
            shutdown(group=group, device=device)
        except Exception:
            logger.warning("aiter providers: %r shutdown() failed", name, exc_info=True)
