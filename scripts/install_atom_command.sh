#!/bin/bash
# Install the `atom` command -- ATOM's conversational deployment agent -- for
# this user, running from this checkout.
#
# No pip and no dependencies: the agent is standard-library Python and drives
# ATOM through docker, so this works on a bare host (including ones whose
# system Python refuses pip installs). System-wide on Ubuntu, use the Debian
# package instead (scripts/build_deb.sh -> amd-atom_<version>_all.deb). Inside
# an ATOM container or a venv, `pip install -e .` provides the same command.
#
# Usage:
#   bash scripts/install_atom_command.sh [BIN_DIR]          # default ~/.local/bin
#   bash scripts/install_atom_command.sh --uninstall [BIN_DIR]
#   PYTHON=/path/to/python3.11 bash scripts/install_atom_command.sh

set -euo pipefail

UNINSTALL=0
FORCE=0
while [ $# -gt 0 ]; do
    case "$1" in
        --uninstall) UNINSTALL=1; shift ;;
        --force) FORCE=1; shift ;;
        -h|--help) sed -n '2,15p' "$0"; exit 0 ;;
        *) break ;;
    esac
done
BIN_DIR="${1:-$HOME/.local/bin}"
TARGET="$BIN_DIR/atom"
MARKER="# atom launcher generated by scripts/install_atom_command.sh"
# The command was briefly called amd-atom; replace that launcher, never
# anything else that happens to have the name.
LEGACY="$BIN_DIR/amd-atom"
LEGACY_MARKER="# amd-atom launcher generated by scripts/install_amd_atom.sh"

ours() { [ -f "$1" ] && grep -qF "$2" "$1"; }

remove_legacy() {
    if ours "$LEGACY" "$LEGACY_MARKER"; then
        rm -f "$LEGACY"
        echo "removed the earlier launcher $LEGACY"
    fi
}

if [ "$UNINSTALL" -eq 1 ]; then
    if ours "$TARGET" "$MARKER"; then
        rm -f "$TARGET"
        echo "removed $TARGET"
    else
        echo "nothing to remove: $TARGET is absent or was not installed by this script"
    fi
    remove_legacy
    exit 0
fi

REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
if [ ! -f "$REPO_ROOT/atom/agent/cli.py" ]; then
    echo "error: $REPO_ROOT has no atom/agent; run this from an ATOM checkout" >&2
    exit 1
fi

PY="$(command -v "${PYTHON:-python3}" || true)"
if [ -z "$PY" ]; then
    echo "error: ${PYTHON:-python3} not found; set PYTHON=/path/to/python3" >&2
    exit 1
fi
if ! "$PY" -c 'import sys; sys.exit(sys.version_info < (3, 10))'; then
    echo "error: $PY is $("$PY" -V 2>&1); atom needs Python 3.10+" >&2
    exit 1
fi

if [ -e "$TARGET" ] && ! ours "$TARGET" "$MARKER" && [ "$FORCE" -eq 0 ]; then
    echo "error: $TARGET exists and was not installed by this script (use --force)" >&2
    echo "       (an old Atom editor install also provides 'atom')" >&2
    exit 1
fi

mkdir -p "$BIN_DIR"
TMP="$(mktemp "$BIN_DIR/.atom.XXXXXX")"
# python -I: the user's PYTHONPATH, user site-packages and -- above all -- the
# current directory stay out of sys.path, so running `atom` inside another
# ATOM checkout still runs this one.
cat > "$TMP" <<EOF
#!/bin/sh
$MARKER
# from $REPO_ROOT. Re-run that script after moving the checkout.
ATOM_AGENT_REPO='$REPO_ROOT'
if [ ! -f "\$ATOM_AGENT_REPO/atom/agent/cli.py" ]; then
    echo "atom: \$ATOM_AGENT_REPO no longer has atom/agent;" \\
         "re-run scripts/install_atom_command.sh from your ATOM checkout" >&2
    exit 1
fi
exec '$PY' -I -c 'import sys; sys.path.insert(0, sys.argv.pop(1)); from atom.agent.cli import main; main()' "\$ATOM_AGENT_REPO" "\$@"
EOF
chmod 755 "$TMP"
mv -f "$TMP" "$TARGET"

if ! "$TARGET" --help >/dev/null 2>&1; then
    echo "error: $TARGET --help failed:" >&2
    "$TARGET" --help >&2 || true
    exit 1
fi
remove_legacy
echo "installed $TARGET -> $REPO_ROOT (python: $PY)"
case ":$PATH:" in
    *":$BIN_DIR:"*)
        FIRST="$(command -v atom || true)"
        if [ -n "$FIRST" ] && [ "$FIRST" != "$TARGET" ]; then
            echo "note: '$FIRST' comes earlier on PATH and will run instead"
        else
            echo "run: atom"
        fi ;;
    *) echo "note: $BIN_DIR is not on PATH; add it, e.g.:"
       echo "  echo 'export PATH=\"$BIN_DIR:\$PATH\"' >> ~/.bashrc && source ~/.bashrc" ;;
esac
