"""vime CLI hook functions for AtomRL injection.

Usage — pass each function via its dotted import path::

    python train.py \\
      --custom-megatron-init-path  atomrl.plugin.vime.hooks.custom_megatron_init \\
      --custom-model-provider-path atomrl.plugin.vime.hooks.custom_model_provider \\
      --rollout-function-path      atomrl.plugin.vime.hooks.generate_rollout

All logic is delegated to existing AtomRL modules.
"""

from __future__ import annotations

import logging
from argparse import Namespace
from typing import Any

from atomrl.plugin import _megatron_hooks
from atomrl.plugin._sglang_host_rollout import generate_rollout as _generate_rollout

logger = logging.getLogger(__name__)


# ---------------------------------------------------------------------------
# Hook 1: --custom-megatron-init-path
# Signature: def custom_init(args: Namespace) -> None
# Called at the end of vime/backends/megatron_utils/initialize.py:init()
# ---------------------------------------------------------------------------


def custom_megatron_init(args: Namespace) -> None:
    """Set up Lumen FP8 training after Megatron distributed init."""
    _megatron_hooks.megatron_init(args)


# ---------------------------------------------------------------------------
# Hook 2: --custom-model-provider-path
# Signature: def custom_model_provider(
#     pre_process: bool, post_process: bool, vp_stage: int | None = None
# ) -> GPTModel
# Called from vime/backends/megatron_utils/model_provider.py
# ---------------------------------------------------------------------------


def custom_model_provider(
    pre_process: bool,
    post_process: bool,
    vp_stage: int | None = None,
):
    """Build a Megatron GPTModel and optionally enable Lumen FP8."""
    return _megatron_hooks.model_provider(pre_process, post_process, vp_stage)


# ---------------------------------------------------------------------------
# Hook 3: --rollout-function-path
# Signature: def generate_rollout(
#     args, rollout_id: int, data_source, evaluation: bool = False
# ) -> RolloutFnTrainOutput | RolloutFnEvalOutput
# Called from vime/ray/rollout/rollout_manager.py
# ---------------------------------------------------------------------------


def generate_rollout(
    args: Any,
    rollout_id: int,
    data_source: Any,
    evaluation: bool = False,
):
    """Return vime-native rollout output generated by ATOM."""
    return _generate_rollout(
        "vime",
        args,
        rollout_id,
        data_source,
        evaluation=evaluation,
    )


def custom_megatron_post_save_hook(
    args: Any,
    rollout_id: int,
    checkpoint_dir: str,
    hf_checkpoint_dir: str,
) -> None:
    """Host-compatible post-save hook."""
    _megatron_hooks.post_save_hook(
        args,
        rollout_id,
        checkpoint_dir,
        hf_checkpoint_dir,
    )


def custom_megatron_before_train_step_hook(
    args: Any,
    rollout_id: int,
    step_id: int,
    model: Any,
    optimizer: Any,
    opt_param_scheduler: Any,
) -> None:
    """Reset Lumen FP8 state before a training step."""
    _megatron_hooks.reset_fp8_state(args, model)


def custom_megatron_before_log_prob_hook(
    args: Any,
    model: Any,
    store_prefix: str,
) -> None:
    """Reset Lumen FP8 state before log-prob computation."""
    _megatron_hooks.reset_fp8_state(args, model)


def custom_update_weight_post_write(
    args: Any,
    version_dir: str,
    rollout_engines: list,
) -> None:
    """Reload ATOM after the host writes an HF checkpoint."""
    _megatron_hooks.update_weight_post_write(args, version_dir, rollout_engines)
