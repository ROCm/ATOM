"""Top-level CLI hooks for miles integration."""

from __future__ import annotations

from argparse import Namespace
from typing import Any

from atomrl.plugin import _megatron_hooks
from atomrl.plugin._sglang_host_rollout import generate_rollout as _generate_rollout


def custom_megatron_init(args: Namespace) -> None:
    """Set up Lumen FP8 after Megatron distributed initialization."""
    _megatron_hooks.megatron_init(args)


def custom_model_provider(
    pre_process: bool,
    post_process: bool,
    vp_stage: int | None = None,
):
    """Build a Megatron GPTModel and optionally enable Lumen FP8."""
    return _megatron_hooks.model_provider(pre_process, post_process, vp_stage)


def generate_rollout(
    args: Any,
    rollout_id: int,
    data_source: Any,
    evaluation: bool = False,
):
    """Return miles-native rollout output generated by ATOM."""
    return _generate_rollout(
        "miles",
        args,
        rollout_id,
        data_source,
        evaluation=evaluation,
    )


def custom_megatron_post_save_hook(
    args: Any,
    rollout_id: int,
    checkpoint_dir: str,
    hf_checkpoint_dir: str,
) -> None:
    """Host-compatible post-save hook."""
    _megatron_hooks.post_save_hook(
        args,
        rollout_id,
        checkpoint_dir,
        hf_checkpoint_dir,
    )


def custom_megatron_before_train_step_hook(
    args: Any,
    rollout_id: int,
    step_id: int,
    model: Any,
    optimizer: Any,
    opt_param_scheduler: Any,
) -> None:
    """Reset Lumen FP8 state before a training step."""
    _megatron_hooks.reset_fp8_state(args, model)


def custom_megatron_before_log_prob_hook(
    args: Any,
    model: Any,
    store_prefix: str,
) -> None:
    """Reset Lumen FP8 state before log-prob computation."""
    _megatron_hooks.reset_fp8_state(args, model)


def custom_update_weight_post_write(
    args: Any,
    version_dir: str,
    rollout_engines: list,
) -> None:
    """Reload ATOM after miles writes an HF checkpoint."""
    _megatron_hooks.update_weight_post_write(args, version_dir, rollout_engines)
